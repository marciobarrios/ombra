function quote(name: string): string {
  return JSON.stringify(name);
}

function objectChecks(id: string, label: string, table: ObjectTable): string[] {
  const listed = table.entries.map((entry) => quote(entry.name)).join(" | ") || "never";
  const base = table.base ?? "Record<never, never>";

  const lines = [
    `// ${label}`,
    `type ${id} = ${table.of};`,
    `export type ${id}Listed = Expect<Equal<Unlisted<${id}, ${base}, ${listed}>, never>>;`,
  ];

  if (table.base)
    lines.push(`export type ${id}Base = Expect<${id} extends ${base} ? true : false>;`);

  table.entries.forEach((entry, index) => {
    const key = `${id}[${quote(entry.name)}]`;
    const required = entry.required === true;

    lines.push(`// ${label} › ${entry.name}`);
    lines.push(
      required
        ? `export type ${id}Type${index} = Expect<Equal<${key}, ${entry.type}>>;`
        : `export type ${id}Type${index} = Expect<Equal<${key} | undefined, (${entry.type}) | undefined>>;`,
    );
    lines.push(
      `export type ${id}Required${index} = Expect<Equal<IsRequired<${id}, ${quote(entry.name)}>, ${required}>>;`,
    );

    if (entry.default !== undefined) {
      lines.push(
        `export const ${id}Default${index}: Exclude<${key}, undefined> = ${entry.default};`,
      );
    }
  });

  return lines;
}

function parameterChecks(id: string, label: string, table: ParameterTable): string[] {
  const total = table.entries.length;
  const required = table.entries.filter((entry) => entry.required).length;
  const lengths = Array.from({ length: total - required + 1 }, (_, index) => required + index);

  const lines = [
    `// ${label}`,
    `type ${id} = Parameters<typeof ${table.of}>;`,
    `export type ${id}Length = Expect<Equal<${id}["length"], ${lengths.join(" | ")}>>;`,
  ];

  table.entries.forEach((entry, index) => {
    lines.push(`// ${label} › ${entry.name}`);
    lines.push(
      entry.required
        ? `export type ${id}Type${index} = Expect<Equal<${id}[${index}], ${entry.type}>>;`
        : `export type ${id}Type${index} = Expect<Equal<${id}[${index}] | undefined, (${entry.type}) | undefined>>;`,
    );
  });

  return lines;
}

function tableChecks(id: string, label: string, table: ApiTable): string[] {
  switch (table.kind) {
    case "object":
      return objectChecks(id, label, table);
    case "parameters":
      return parameterChecks(id, label, table);
  }
}

const body = listApiParts().flatMap((part, partIndex) => {
  const lines = part.tables.flatMap((table, tableIndex) =>
    tableChecks(`Part${partIndex}Table${tableIndex}`, `${part.name} › ${table.title}`, table),
  );

  if (part.returns !== undefined) {
    lines.push(`// ${part.name} › Returns`);
    lines.push(
      `export type Part${partIndex}Returns = Expect<Equal<ReturnType<typeof ${part.name}>, ${part.returns}>>;`,
    );
  }

  return ["", ...lines];
});

writeFileSync(out, `${header}${body.join("\n")}\n`);
